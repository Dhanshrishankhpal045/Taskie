export const generateMeetingReport = (
  meeting: Meeting
): string => {
  const decisions =
    meeting.decisions &&
    meeting.decisions.length > 0
      ? meeting.decisions
          .map(
            (decision, index) =>
              `${index + 1}. ${decision}`
          )
          .join("\n")
      : "No decisions identified.";

  const actionItems =
    meeting.actionItems &&
    meeting.actionItems.length > 0
      ? meeting.actionItems
          .map((item, index) => {
            const details = [
              `Status: ${getActionItemStatus(
                item.status
              )}`,

              item.assignee
                ? `Assignee: ${item.assignee}`
                : "",

              item.dueDate
                ? `Due Date: ${formatDate(
                    item.dueDate
                  )}`
                : "",

              item.priority
                ? `Priority: ${item.priority}`
                : "",
            ].filter(Boolean);

            return [
              `${index + 1}. ${item.text}`,

              ...details.map(
                (detail) =>
                  `   ${detail}`
              ),
            ].join("\n");
          })
          .join("\n\n")
      : "No action items identified.";

  const unresolvedQuestions =
    meeting.unresolvedQuestions &&
    meeting.unresolvedQuestions.length > 0
      ? meeting.unresolvedQuestions
          .map(
            (question, index) =>
              `${index + 1}. ${question}`
          )
          .join("\n")
      : "No unresolved questions identified.";

  const report = `
============================================================
                         TASKIE
                  MEETING INTELLIGENCE
============================================================

MEETING
------------------------------------------------------------

Title:
${meeting.title}

Date:
${formatDate(meeting.createdAt)}

Analysis Status:
${getStatus(meeting.analysisStatus)}


SUMMARY
------------------------------------------------------------

${meeting.summary || "No summary available."}


AI NOTES
------------------------------------------------------------

${meeting.aiNotes || "No AI notes available."}


PERSONAL NOTES
------------------------------------------------------------

${meeting.personalNotes || "No personal notes available."}


DECISIONS
------------------------------------------------------------

${decisions}


ACTION ITEMS
------------------------------------------------------------

${actionItems}


UNRESOLVED QUESTIONS
------------------------------------------------------------

${unresolvedQuestions}


TRANSCRIPT
------------------------------------------------------------

${meeting.transcript || "No transcript available."}


============================================================
                    Generated by Taskie
              From Conversation → to Verified Execution
============================================================
`.trim();

  return report;
};

/* -------------------------------- */
/* TXT DOWNLOAD */
/* -------------------------------- */

export const downloadMeetingReport = (
  meeting: Meeting
) => {
  const report =
    generateMeetingReport(meeting);

  const blob = new Blob(
    [report],
    {
      type: "text/plain;charset=utf-8",
    }
  );

  const safeTitle =
    createSafeFileName(
      meeting.title
    );

  downloadBlob(
    blob,
    `taskie-${safeTitle}-report.txt`
  );
};

