export const generateMeetingJson = (
  meeting: Meeting
) => {
  return {
    application: "Taskie",

    tagline:
      "From Conversation → to Verified Execution",

    meeting: {
      id: meeting._id,

      title: meeting.title,

      createdAt:
        meeting.createdAt || null,

      updatedAt:
        meeting.updatedAt || null,

      analysisStatus:
        meeting.analysisStatus ||
        "pending",

      summary:
        meeting.summary || "",

      aiNotes:
        meeting.aiNotes || "",

      personalNotes:
        meeting.personalNotes || "",

      decisions:
        meeting.decisions || [],

      actionItems:
        (meeting.actionItems || []).map(
          (item, index) => ({
            index,

            actionItemId:
              item.actionItemId ||
              null,

            text: item.text,

            assignee:
              item.assignee || "",

            dueDate:
              item.dueDate || null,

            priority:
              item.priority ||
              "medium",

            status: item.status,
          })
        ),

      unresolvedQuestions:
        meeting.unresolvedQuestions ||
        [],

      transcript:
        meeting.transcript || "",
    },
  };
};

